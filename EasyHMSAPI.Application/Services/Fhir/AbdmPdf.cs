using System.Globalization;
using System.Text;

namespace EasyHMSAPI.Application.Services.Fhir
{
    /// <summary>One block of a printed record: a heading and its lines (each line wraps).</summary>
    public sealed record AbdmPdfSection(string Heading, IReadOnlyList<string> Lines);

    /// <summary>What a printed ABDM record shows: who issued it, what it is, the identity block
    /// (patient and doctor, as label/value pairs), then the record's own sections.</summary>
    public sealed record AbdmPdfDocument(
        string FacilityName,
        string Title,
        IReadOnlyList<(string Label, string? Value)> Identity,
        IReadOnlyList<AbdmPdfSection> Sections,
        string? Footer = null);

    /// <summary>
    /// The unstructured (PDF) copy NHA asks for beside each structured record (M2 workbook,
    /// HIP_INIT_SHARE_CARECONTEXT note 1). A small, dependency-free PDF 1.4 writer: A4 pages, the
    /// standard Helvetica fonts every PDF reader carries (nothing embedded, so it works in the
    /// Linux container with no font files), word wrap and page breaks. Text is Latin-1; anything
    /// outside it prints as "?", which keeps the file valid. Records are printed in English.
    /// </summary>
    public static class AbdmPdf
    {
        private const float PageWidth = 595.28f;
        private const float PageHeight = 841.89f;
        private const float Margin = 48f;
        private const float BodySize = 10f;
        private const float BodyLeading = 14f;

        public static byte[] Render(AbdmPdfDocument document)
        {
            var layout = new Layout();
            layout.Text(document.FacilityName, 14f, bold: true, leading: 18f);
            layout.Text(document.Title, 12f, bold: true, leading: 18f);
            layout.Rule();

            foreach (var (label, value) in document.Identity)
            {
                if (string.IsNullOrWhiteSpace(value))
                    continue;
                layout.Pair(label, value!.Trim());
            }
            layout.Gap(6f);
            layout.Rule();

            foreach (var section in document.Sections)
            {
                var lines = section.Lines.Where(l => !string.IsNullOrWhiteSpace(l)).ToList();
                if (lines.Count == 0)
                    continue;
                layout.KeepTogether(BodyLeading * 2 + 6f);
                layout.Gap(4f);
                layout.Text(section.Heading, 11f, bold: true, leading: 16f);
                foreach (var line in lines)
                    foreach (var paragraph in line.Replace("\r", string.Empty).Split('\n'))
                        layout.Text(paragraph, BodySize, bold: false, leading: BodyLeading);
            }

            layout.Gap(10f);
            layout.Text(document.Footer ?? "Shared through the Ayushman Bharat Digital Mission (ABDM). Generated by 1HMS.", 8f, bold: false, leading: 11f);
            return WriteFile(layout.Finish());
        }

        // ---- layout --------------------------------------------------------------------------

        private sealed class Layout
        {
            private StringBuilder _page = new();
            private float _y = PageHeight - Margin;
            private readonly List<string> _pages = new();

            public void Text(string text, float size, bool bold, float leading)
            {
                foreach (var line in Wrap(text, size, bold, PageWidth - 2 * Margin))
                {
                    NeedRoom(leading);
                    _y -= leading;
                    Show(Margin, _y, size, bold, line);
                }
            }

            public void Pair(string label, string value)
            {
                const float labelWidth = 130f;
                var lines = Wrap(value, BodySize, false, PageWidth - 2 * Margin - labelWidth);
                for (var i = 0; i < lines.Count; i++)
                {
                    NeedRoom(BodyLeading);
                    _y -= BodyLeading;
                    if (i == 0)
                        Show(Margin, _y, BodySize, true, label);
                    Show(Margin + labelWidth, _y, BodySize, false, lines[i]);
                }
            }

            public void Gap(float height)
            {
                if (_y - height > Margin)
                    _y -= height;
            }

            public void Rule()
            {
                NeedRoom(8f);
                _y -= 6f;
                _page.Append(F(Margin)).Append(' ').Append(F(_y)).Append(" m ")
                    .Append(F(PageWidth - Margin)).Append(' ').Append(F(_y)).Append(" l 0.5 w S\n");
            }

            public void KeepTogether(float height) => NeedRoom(height);

            private void NeedRoom(float height)
            {
                if (_y - height >= Margin)
                    return;
                Flush();
                _y = PageHeight - Margin;
            }

            private void Show(float x, float y, float size, bool bold, string text)
            {
                _page.Append("BT /").Append(bold ? "F2" : "F1").Append(' ').Append(F(size)).Append(" Tf ")
                    .Append(F(x)).Append(' ').Append(F(y)).Append(" Td (").Append(Escape(text)).Append(") Tj ET\n");
            }

            private void Flush()
            {
                _pages.Add(_page.ToString());
                _page = new StringBuilder();
            }

            public List<string> Finish()
            {
                Flush();
                return _pages;
            }
        }

        /// <summary>Breaks text into lines no wider than <paramref name="width"/> points; a word longer
        /// than a line is cut.</summary>
        public static List<string> Wrap(string text, float size, bool bold, float width)
        {
            var lines = new List<string>();
            var words = Clean(text).Split(' ', StringSplitOptions.RemoveEmptyEntries);
            var current = new StringBuilder();
            foreach (var word in words)
            {
                var candidate = current.Length == 0 ? word : current + " " + word;
                if (Measure(candidate, size, bold) <= width)
                {
                    current.Clear().Append(candidate);
                    continue;
                }
                if (current.Length > 0)
                {
                    lines.Add(current.ToString());
                    current.Clear();
                }
                var rest = word;
                while (Measure(rest, size, bold) > width)
                {
                    var cut = rest.Length - 1;
                    while (cut > 1 && Measure(rest[..cut], size, bold) > width)
                        cut--;
                    lines.Add(rest[..cut]);
                    rest = rest[cut..];
                }
                current.Append(rest);
            }
            if (current.Length > 0 || lines.Count == 0)
                lines.Add(current.ToString());
            return lines;
        }

        /// <summary>Text width in points, from Helvetica's metrics (bold set 6% wider, which errs on
        /// the side of wrapping early).</summary>
        public static float Measure(string text, float size, bool bold)
        {
            var units = 0;
            foreach (var c in text)
                units += c >= 32 && c <= 126 ? Widths[c - 32] : 556;
            return units * size / 1000f * (bold ? 1.06f : 1f);
        }

        // Helvetica advance widths for ' ' (32) to '~' (126), in 1/1000 em (Adobe AFM).
        private static readonly int[] Widths =
        {
            278, 278, 355, 556, 556, 889, 667, 191, 333, 333, 389, 584, 278, 333, 278, 278,
            556, 556, 556, 556, 556, 556, 556, 556, 556, 556, 278, 278, 584, 584, 584, 556,
            1015, 667, 667, 722, 722, 667, 611, 778, 722, 278, 500, 667, 556, 833, 722, 778,
            667, 778, 722, 667, 611, 722, 667, 944, 667, 667, 611, 278, 278, 278, 469, 556,
            333, 556, 556, 500, 556, 556, 278, 556, 556, 222, 222, 500, 222, 833, 556, 556,
            556, 556, 333, 500, 278, 556, 500, 722, 500, 500, 500, 334, 260, 334, 584
        };

        private static string Clean(string text)
        {
            var builder = new StringBuilder(text.Length);
            foreach (var c in text)
            {
                if (c == '\t' || c == '\n' || c == '\r') builder.Append(' ');
                else if (c < 32) continue;
                else if (c <= 255) builder.Append(c);
                else builder.Append(c switch { '‘' or '’' => '\'', '“' or '”' => '"', '–' or '—' => '-', '₹' => 'R', _ => '?' });
            }
            return builder.ToString();
        }

        private static string Escape(string text) =>
            Clean(text).Replace("\\", "\\\\").Replace("(", "\\(").Replace(")", "\\)");

        private static string F(float value) => value.ToString("0.##", CultureInfo.InvariantCulture);

        // ---- file ----------------------------------------------------------------------------

        private static byte[] WriteFile(List<string> pages)
        {
            var latin1 = Encoding.Latin1;
            using var output = new MemoryStream();
            var offsets = new List<long>();

            void Raw(string s)
            {
                var bytes = latin1.GetBytes(s);
                output.Write(bytes, 0, bytes.Length);
            }
            void Object(int number, string body)
            {
                while (offsets.Count < number) offsets.Add(0);
                offsets[number - 1] = output.Position;
                Raw($"{number} 0 obj\n{body}\nendobj\n");
            }

            // 1 catalog, 2 page tree, 3 Helvetica, 4 Helvetica-Bold, then a page and its content per page.
            var pageCount = pages.Count;
            var kids = string.Join(' ', Enumerable.Range(0, pageCount).Select(i => $"{5 + 2 * i} 0 R"));
            Raw("%PDF-1.4\n%âãÏÓ\n");
            Object(1, "<< /Type /Catalog /Pages 2 0 R >>");
            Object(2, $"<< /Type /Pages /Kids [{kids}] /Count {pageCount} >>");
            Object(3, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>");
            Object(4, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>");
            for (var i = 0; i < pageCount; i++)
            {
                var pageNumber = 5 + 2 * i;
                Object(pageNumber, $"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {F(PageWidth)} {F(PageHeight)}] " +
                    $"/Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents {pageNumber + 1} 0 R >>");
                var content = pages[i];
                Object(pageNumber + 1, $"<< /Length {latin1.GetByteCount(content)} >>\nstream\n{content}endstream");
            }

            var xref = output.Position;
            var table = new StringBuilder();
            table.Append("xref\n0 ").Append(offsets.Count + 1).Append('\n').Append("0000000000 65535 f \n");
            foreach (var offset in offsets)
                table.Append(offset.ToString("D10", CultureInfo.InvariantCulture)).Append(" 00000 n \n");
            table.Append("trailer\n<< /Size ").Append(offsets.Count + 1).Append(" /Root 1 0 R >>\nstartxref\n")
                .Append(xref.ToString(CultureInfo.InvariantCulture)).Append("\n%%EOF\n");
            Raw(table.ToString());
            return output.ToArray();
        }
    }
}
